    private var currentLocale: Locale = Locale.ENGLISH

    /** Call from MainApp when language is toggled. */
    fun setLanguage(locale: Locale) { currentLocale = locale }

    fun setLanguageCode(code: String) {
        currentLocale = if (code == "th") Locale("th", "TH") else Locale.ENGLISH
    }

    fun isThai(): Boolean = currentLocale.language == "th"

    fun get(key: String): String = if (isThai()) th[key] ?: en[key] ?: "??$key??" else en[key] ?: "??$key??"

    /** For strings with format args, e.g. t(StringKeys.NO_API_KEY, providerLabel) */
    fun fmt(key: String, vararg args: Any?): String = String.format(java.util.Locale.US, get(key), *args)

    /** Convenience: translate and format. */
    fun t(key: String): String = get(key)
